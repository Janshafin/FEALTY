/**
 * Writes typed ABIs into packages/shared/src/abis from Foundry build output and the pinned ENSv2
 * deployment set. Run after `forge build`: `npx tsx scripts/gen-abis.ts`.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const out = resolve(root, "packages/shared/src/abis")
mkdirSync(out, { recursive: true })

const ensDeploy = resolve(root, "contracts/lib/contracts-v2/contracts/deployments/sepolia")

const sources: { name: string; file: string; pick: (j: any) => unknown }[] = [
  { name: "throneAbi", file: resolve(root, "contracts/out/Throne.sol/Throne.json"), pick: (j) => j.abi },
  { name: "courtAbi", file: resolve(root, "contracts/out/FealtyCourt.sol/FealtyCourt.json"), pick: (j) => j.abi },
  {
    name: "permissionedResolverAbi",
    file: resolve(root, "contracts/out/PermissionedResolver.sol/PermissionedResolver.json"),
    pick: (j) => j.abi,
  },
  { name: "universalResolverAbi", file: resolve(ensDeploy, "UniversalResolverV2.json"), pick: (j) => j.abi },
  { name: "ethRegistrarAbi", file: resolve(ensDeploy, "ETHRegistrar.json"), pick: (j) => j.abi },
  { name: "worldIdAbi", file: resolve(root, "contracts/out/IWorldID.sol/IWorldID.json"), pick: (j) => j.abi },
]

const index: string[] = []
for (const s of sources) {
  const abi = s.pick(JSON.parse(readFileSync(s.file, "utf8")))
  const file = s.name.replace(/Abi$/, "").replace(/[A-Z]/g, (c) => "-" + c.toLowerCase()).replace(/^-/, "")
  writeFileSync(
    resolve(out, `${file}.ts`),
    `// Generated by scripts/gen-abis.ts. Do not edit.\nexport const ${s.name} = ${JSON.stringify(abi, null, 2)} as const\n`,
  )
  index.push(`export { ${s.name} } from "./${file}.js"`)
  console.log(`wrote ${file}.ts`)
}
writeFileSync(resolve(out, "index.ts"), `// Generated by scripts/gen-abis.ts. Do not edit.\n${index.join("\n")}\n`)
